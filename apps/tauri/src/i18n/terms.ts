/**
 * Game-term dictionary (owner 10-23). Resolves a server-authored ENGLISH term (skill, position, race/roster name,
 * inducement, star player, injury name, weather, kickoff event) to the active locale's term. English is the identity.
 *
 * Lookup is forgiving, because the server, the client catalogues and the source dictionary spell the same term
 * differently: case, spacing, hyphens and apostrophes are ignored ("Re-roll" = "Reroll" = "re roll", "Dump-Off" =
 * "Dump-off", "Kick 'em" = "Kick ’em"), and a trailing parenthetical is kept but not matched ("Mighty Blow (+2)" uses
 * "Mighty Blow" and re-appends " (+2)"; "Loner (4+)" likewise).
 *
 * English (US) and English (UK) both use the identity: game terms (skills, traits, positions, kick-off events such as
 * "Solid Defence", and "Armour") are the rulebook's own names and are spelled the same in both Englishes.
 *
 * Unknown terms come back unchanged (English), and are reported once to the dev console only.
 *
 * `locales/zh-Hans.terms.json` is GENERATED by scripts/build-terms.mjs from user-supplied community data (short names
 * only: rules passages are dropped there and never ship). The other `locales/<locale>.terms.json` files (Lane C, owner
 * 10-23) are machine-translated name lists over the same English keys: NAMES only, never rules text. Published-edition
 * terms where they exist (fr/de/es/it/pl), community usage elsewhere, coined terms for ga/gd/cy (flagged in
 * `sources/<locale>.terms.notes.md`); each locale's vocabulary conventions are in `sources/<locale>.glossary.md`.
 */

export type TermsLocale = Locale;
type TermTable = Readonly<Record<string, string>>;

const TABLES: Readonly<Record<Exclude<TermsLocale, 'en' | 'en-GB'>, TermTable>> = {
  bg: bgTerms as TermTable,
  cy: cyTerms as TermTable,
  de: deTerms as TermTable,
  es: esTerms as TermTable,
  fr: frTerms as TermTable,
  ga: gaTerms as TermTable,
  gd: gdTerms as TermTable,
  it: itTerms as TermTable,
  nl: nlTerms as TermTable,
  pl: plTerms as TermTable,
  ru: ruTerms as TermTable,
  'sr-Cyrl': srCyrlTerms as TermTable,
  'sr-Latn': srLatnTerms as TermTable,
  uk: ukTerms as TermTable,
  'zh-Hans': zhHansTerms as TermTable,
};

/** Normalised lookup key: case/spacing/hyphen/apostrophe/quote/punctuation-insensitive. */
export function termKey(term: string): string {
  return term
    .normalize('NFKC')
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^\p{L}\p{N}+]/gu, '');
}

const TRAILING_PAREN = /^(.*?\S)\s*(\([^()]*\))\s*$/;

const indexCache = new Map<TermsLocale, Map<string, string>>();
function indexFor(locale: Exclude<TermsLocale, 'en' | 'en-GB'>): Map<string, string> {
  let index = indexCache.get(locale);
  if (!index) {
    index = new Map();
    for (const [english, translated] of Object.entries(TABLES[locale])) {
      const key = termKey(english);
      if (key && !index.has(key)) index.set(key, translated);
    }
    indexCache.set(locale, index);
  }
  return index;
}

const warned = new Set<string>();
function warnUnresolved(locale: TermsLocale, term: string): void {
  const id = `${locale}\u0000${term}`;
  if (warned.has(id)) return;
  warned.add(id);
  if ((import.meta as { env?: { DEV?: boolean } }).env?.DEV) {
    try { console.debug(`[i18n] no ${locale} term for "${term}"`); } catch { /* ignore */ }
  }
}

/** The translated term, or null when the dictionary has none (tests / coverage tooling). */
export function lookupTerm(term: string, locale: TermsLocale): string | null {
  if (locale === 'en' || locale === 'en-GB') return term; // game terms are the rulebook's names in both Englishes
  const trimmed = term.replace(/\s+/g, ' ').trim();
  if (!trimmed) return null;
  const index = indexFor(locale);
  const direct = index.get(termKey(trimmed));
  if (direct !== undefined) return direct;
  const paren = TRAILING_PAREN.exec(trimmed);
  if (paren) {
    const base = index.get(termKey(paren[1]!));
    if (base !== undefined) return `${base} ${paren[2]}`;
  }
  // Quoted names ("Blastin' Solves Everything") match with or without their quotes.
  const unquoted = trimmed.replace(/^["“”']+|["“”']+$/g, '');
  if (unquoted !== trimmed) {
    const q = index.get(termKey(unquoted));
    if (q !== undefined) return q;
  }
  return null;
}

/** A server term in the active locale; the English term unchanged when untranslated. Null/undefined -> ''. */
export function terms(term: string | null | undefined): string {
  if (term === null || term === undefined) return '';
  const locale = localeRef.value;
  if (locale === 'en' || locale === 'en-GB') return term; // game terms are the rulebook's names in both Englishes
  const found = lookupTerm(term, locale);
  if (found !== null) return found;
  warnUnresolved(locale, term);
  return term;
}

/** Alias reading better at single-term call sites. */
export const term = terms;

/** Lower-case letters and digits only: the shape of a roster / sprite-sheet / position id (`Black Orc` -> `blackorc`). */
const idKey = (value: string): string => value.toLowerCase().replace(/[^a-z0-9]/g, '');
let englishById: Map<string, string> | null = null;
/**
 * The canonical ENGLISH game term whose id-shape equals `id` (`blackorc` -> `Black Orc`, `elvenunion` -> `Elven Union`),
 * from the term dictionaries' English keys (the one place the client keeps those names), else null. The id itself
 * stays DATA; this is for display (pass the result through terms()).
 */
export function englishTermForId(id: string | null | undefined): string | null {
  if (!englishById) {
    englishById = new Map();
    for (const table of Object.values(TABLES)) for (const english of Object.keys(table)) {
      const k = idKey(english);
      if (k && !englishById.has(k)) englishById.set(k, english);
    }
  }
  return englishById.get(idKey(String(id ?? ''))) ?? null;
}
